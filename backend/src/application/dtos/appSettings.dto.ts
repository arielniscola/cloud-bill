import { z } from 'zod';

export const updateAppSettingsSchema = z.object({
  defaultBudgetCashRegisterId:  z.string().uuid().optional().nullable(),
  defaultInvoiceCashRegisterId: z.string().uuid().optional().nullable(),
  deadStockDays:                z.number().int().min(1).max(3650).optional(),
  safetyStockDays:              z.number().int().min(1).max(365).optional(),
  stalePriceWarnDays1:          z.number().int().min(1).max(365).optional(),
  stalePriceWarnDays2:          z.number().int().min(1).max(365).optional(),
  companyTaxCondition:          z.enum(['RESPONSABLE_INSCRIPTO', 'MONOTRIBUTISTA', 'EXENTO', 'CONSUMIDOR_FINAL']).optional(),
  printFormat:                  z.enum(['A4', 'THERMAL_80MM']).optional(),
  printFormatInvoice:           z.enum(['A4', 'THERMAL_80MM']).optional(),
  printFormatBudget:            z.enum(['A4', 'THERMAL_80MM']).optional(),
  printFormatOrdenPedido:       z.enum(['A4', 'THERMAL_80MM']).optional(),
  printFormatRemito:            z.enum(['A4', 'THERMAL_80MM']).optional(),
  printFormatRecibo:            z.enum(['A4', 'THERMAL_80MM']).optional(),
  printFormatCashMovement:      z.enum(['A4', 'THERMAL_80MM']).optional(),
  smtpHost:                     z.string().optional().nullable(),
  smtpPort:                     z.number().int().min(1).max(65535).optional(),
  smtpUser:                     z.string().optional().nullable(),
  smtpPass:                     z.string().optional().nullable(),
  smtpFrom:                     z.string().optional().nullable(),
  smtpSecure:                   z.boolean().optional(),
  mpAccessToken:                z.string().optional().nullable(),
  mpPublicKey:                  z.string().optional().nullable(),
  mpWebhookSecret:              z.string().optional().nullable(),
  mpMode:                       z.enum(['test', 'production']).optional(),
  mpPosId:                      z.string().optional().nullable(),
  defaultRegisterPaymentInvoice:     z.boolean().optional(),
  defaultRegisterPaymentOrdenPedido: z.boolean().optional(),
  timeSurchargeEnabled:              z.boolean().optional(),
  timeSurchargeFrom:                 z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, 'Horario inválido (HH:mm)').optional(),
  timeSurchargeTo:                   z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, 'Horario inválido (HH:mm)').optional(),
  timeSurchargePct:                  z.number().min(0).max(100).optional(),
  defaultInvoiceType:                z.enum(['AUTO', 'FACTURA_A', 'FACTURA_B', 'FACTURA_C']).optional(),
  printWebsite:                      z.string().max(200).optional().nullable(),
  printEstablishment:                z.string().max(50).optional().nullable(),
  remitoCai:                         z.string().max(30).optional().nullable(),
  remitoCaiExpiry:                   z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Fecha inválida (AAAA-MM-DD)').or(z.literal('')).optional().nullable(),
  remitoCopies:                      z.enum(['TWO_PER_PAGE', 'ONE_PER_PAGE', 'SINGLE']).optional(),
});

export type UpdateAppSettingsDTO = z.infer<typeof updateAppSettingsSchema>;
